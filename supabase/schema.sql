  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own projects"
  on public.projects for delete
  using ((select auth.uid()) = user_id);

create table public.todos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  project_id uuid,
  parent_task_id bigint,
  title text not null check (char_length(title) between 1 and 200),
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  deleted_at timestamptz,
  priority text not null default 'none'
    check (priority in ('none', 'low', 'medium', 'high', 'urgent')),
  constraint todos_user_project_fkey
    foreign key (user_id, project_id)
    references public.projects (user_id, id)
    on delete set null (project_id),
  constraint todos_user_id_id_unique unique (user_id, id),
  constraint todos_user_parent_task_fkey
    foreign key (user_id, parent_task_id)
    references public.todos (user_id, id)
    on delete set null (parent_task_id),
  constraint todos_parent_task_not_self_check
    check (parent_task_id is null or parent_task_id <> id)
);

alter table public.todos enable row level security;

revoke all on public.todos from public, anon, authenticated;
revoke all on sequence public.todos_id_seq from public, anon, authenticated;

grant select, insert, update, delete on public.todos to authenticated;
grant usage, select on sequence public.todos_id_seq to authenticated;

