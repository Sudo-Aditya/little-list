create or replace function public.validate_todo_parent_task()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.parent_task_id is null then
    return new;
  end if;
  if new.parent_task_id = new.id then
    raise exception 'A task cannot be its own parent.';
  end if;
  if new.deleted_at is not null then
    raise exception 'A deleted task cannot be a subtask.';
  end if;
  if exists (
    select 1 from public.todos parent
    where parent.user_id = new.user_id
      and parent.id = new.parent_task_id
      and (parent.parent_task_id is not null or parent.deleted_at is not null)
  ) then
    raise exception 'Subtasks can only be added to active top-level tasks.';
  end if;
  if exists (
    select 1 from public.todos child
    where child.user_id = new.user_id
      and child.parent_task_id = new.id
  ) then
    raise exception 'A task with subtasks cannot become a subtask.';
  end if;
  return new;
end;
$$;

create trigger todos_validate_parent_task
  before insert or update of user_id, parent_task_id
  on public.todos
  for each row execute function public.validate_todo_parent_task();

create table public.tags (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null check (name = btrim(name) and char_length(name) between 1 and 40),
  created_at timestamptz not null default now(),
  unique (user_id, id)
);

create unique index tags_user_name_unique
  on public.tags (user_id, lower(name));

create table public.todo_tags (
  user_id uuid not null references auth.users (id) on delete cascade,
  todo_id bigint not null,
  tag_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (user_id, todo_id, tag_id),
  constraint todo_tags_user_todo_fkey
    foreign key (user_id, todo_id)
    references public.todos (user_id, id)
    on delete cascade,
  constraint todo_tags_user_tag_fkey
    foreign key (user_id, tag_id)
    references public.tags (user_id, id)
    on delete cascade
);

create index todo_tags_user_tag_idx
  on public.todo_tags (user_id, tag_id);

