def req(name, method, path, body=None, auth=True, tests=None, raw_body=None, headers_extra=None):
    headers = []
    if auth:
        headers.append({"key": "apikey", "value": "{{anon_key}}"})
        headers.append({"key": "Authorization", "value": "Bearer {{access_token}}"})
    if headers_extra:
        headers.extend(headers_extra)
    item = {
        "name": name,
        "request": {
            "method": method,
            "header": headers,
            "url": {"raw": "{{base_url}}" + path, "host": ["{{base_url}}"], "path": path.strip("/").split("/")},
        },
    }
    if tests:
        item["event"] = [{"listen": "test", "script": {"type": "text/javascript", "exec": tests}}]
    if body is not None:
        item["request"]["body"] = {
            "mode": "raw",
            "raw": json.dumps(body),
            "options": {"raw": {"language": "json"}},
        }
    if raw_body is not None:
        item["request"]["body"] = {"mode": "raw", "raw": raw_body}
    return item


